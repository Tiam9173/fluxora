// https://github.com/unicode-org/cldr/tree/release-48/common/main
String? geoCountryCode(String? value) {
  final name = value?.trim();
  if (name == null || name.isEmpty) return null;
  final code = name.toUpperCase();
  return _countryNames.containsKey(code)
      ? code
      : _codesByName[name.toLowerCase()];
}

